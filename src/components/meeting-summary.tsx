"use client";

import Link from "next/link";
import { useState } from "react";
import type { SessionSnapshot } from "@/lib/session-snapshot";
import type { SummaryReport } from "@/lib/meeting-summary";
import { statusLabels } from "@/lib/rules";

export function MeetingSummary({ data, enabled, save }: {
  data: Pick<SessionSnapshot, "summary" | "state" | "lifecycleVersion">;
  enabled: boolean;
  save: (command: "generate-summary", input: { note: string; version: number }) => Promise<boolean>;
}) {
  const [note, setNote] = useState("");
  const [confirmation, setConfirmation] = useState<{ note: string; version: number } | null>(null);
  const [submitting, setSubmitting] = useState(false);
  const report = data.summary.report;
  const eligible = data.summary.canGenerate && data.state === "CLOSED" && !report;
  const canGenerate = eligible && enabled && !submitting && note.trim().length <= 4000;
  const canConfirm = canGenerate && confirmation !== null && confirmation.version === data.lifecycleVersion;
  return <section className="card" id="meeting-summary" aria-labelledby="meeting-summary-heading">
    <h2 id="meeting-summary-heading">Meeting summary</h2>
    <p>A permanent, non-AI record of submitted context, final topic outcomes and captured commitments; not a transcript.</p>
    {report ? <SavedReport report={report} /> : <p>No summary has been generated.</p>}
    {(eligible || note.length > 0) && <div>
      {report && <p role="status">{note.trim() === report.note
        ? "Your retained draft matches the saved wrap-up. Nothing will be resubmitted."
        : "Your unused note is not included in the saved report. It is retained here until you dismiss it."}</p>}
      {!eligible && !report && <p role="status">Draft retained. Summary creation is not currently available.</p>}
      <label>Facilitator wrap-up (optional)<textarea maxLength={4000} value={note} readOnly={Boolean(report)}
        onChange={event => setNote(event.target.value)} /></label>
      {note.trim().length > 4000 && <p role="alert">Use at most 4000 characters.</p>}
      {report ? <button onClick={() => { setNote(""); setConfirmation(null); }}>Dismiss retained draft</button> : eligible && <>
        <button aria-disabled={!canGenerate} onClick={() => {
          if (canGenerate) setConfirmation({ note, version: data.lifecycleVersion });
        }}>Generate summary</button>
        {confirmation && <div role="group" aria-label="Confirm summary creation">
          <p>Create one permanent report? It cannot be edited or regenerated. Action details are captured at generation, not at meeting close.</p>
          <p className="context">Wrap-up to include: {confirmation.note.trim() || "No wrap-up."}</p>
          <button aria-disabled={!canConfirm} onClick={async () => {
            if (!canConfirm) return;
            setSubmitting(true);
            try {
              if (await save("generate-summary", { ...confirmation })) setConfirmation(null);
            } finally { setSubmitting(false); }
          }}>Confirm generate summary</button>
          <button onClick={() => setConfirmation(null)}>Cancel summary creation</button>
          {confirmation.version !== data.lifecycleVersion && <p role="status">Session changed. Cancel and review its current state before confirming.</p>}
        </div>}
      </>}
    </div>}
  </section>;
}

function SavedReport({ report }: { report: SummaryReport }) {
  const content = report.content;
  return <section aria-label="Saved meeting summary">
    <p>Generated by {report.generatedBy.name} / Source captured at <time dateTime={report.generatedAt}>{report.generatedAt}</time></p>
    <h3>{content.session.title}</h3>
    <p>Facilitator: {content.session.facilitator.name}</p>
    <h3>Joined participants</h3>
    <p>Historical joining, including removed participants; not attendance or current permission to contribute.</p>
    <ul>{content.participants.map(item => <li key={item.id}>{item.name} / Joined: {item.joinedAt}</li>)}</ul>
    <h3>Facilitator-written wrap-up</h3><p className="context">{report.note || "No facilitator wrap-up provided."}</p>
    <p>Voting: {content.votingState === "FINALIZED" ? "Finalized" : "Not held"}</p>
    <h3>Topic outcomes</h3>
    {!content.topics.length && <p>No active topics were captured.</p>}
    {content.topics.map(item => <article key={item.id}>
      <h4>{item.title}</h4><p className="context">{item.description}</p>
      {item.originalPosition !== null && <p>Original vote rank: {item.originalPosition} / Votes: {item.voteCount} / Plan slot: {item.discussionPosition}</p>}
      <p>Outcome: {item.outcome === "DISCUSSED" ? "Discussed" : item.outcome === "DEFERRED" ? "Deferred" : "Not discussed"}</p>
      {item.reason !== null && <p className="context">Latest parked reason: {item.reason}</p>}
    </article>)}
    <h3>Action details at summary generation</h3>
    <p>These are captured values, not necessarily values at meeting close. Action links show current details; later progress does not rewrite this report.</p>
    {!content.actions.length && <p>No actions were created or reviewed in this session.</p>}
    {content.actions.map(item => <article key={item.id}>
      <h4>{item.title}</h4><p className="context">{item.context}</p>
      <p>Owner: {item.owner.name}</p><p>Status at generation: {statusLabels[item.status]}</p>
      <p>Due: {item.dueDate ?? "Not set"}</p>
      <p>{item.createdHere ? "Created here" : "Reviewed here"} / Source: {item.source.title}</p>
      <Link href={`/actions/${item.id}`}>View current action: {item.title}</Link>
      {item.reviews.map(review => <div key={review.id}>
        <p className="context">{review.note}</p>
        <p>Recorded result: {statusLabels[review.resultingStatus]} / By {review.actor.name} / {review.createdAt}</p>
      </div>)}
    </article>)}
    <p><Link href={`/sessions/${content.session.id}`}>View protected source history</Link></p>
    <a href="#meeting-summary">Link to this summary</a>
  </section>;
}
